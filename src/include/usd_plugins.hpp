#pragma once

#include "duckdb.hpp"

namespace duckdb {

//! A runtime resource of OpenUSD (a plugInfo.json or generatedSchema.usda) compiled into the extension
struct UsdEmbeddedResource {
	//! Path relative to OpenUSD's lib/usd directory, e.g. "usdGeom/resources/plugInfo.json"
	const char *path;
	const unsigned char *data;
	idx_t size;
};

//! Generated by cmake/UsdEmbedResources.cmake
extern const UsdEmbeddedResource USD_EMBEDDED_RESOURCES[];
extern const idx_t USD_EMBEDDED_RESOURCE_COUNT;
extern const char USD_EMBEDDED_RESOURCE_HASH[];

//! Makes OpenUSD's file formats, asset resolver and schemas available: writes the embedded plugin resources to a
//! private directory, registers them and installs the extension's asset resolver. Must run before any other OpenUSD
//! call. Throws an IOException on failure. Safe to call more than once.
void UsdRegisterPlugins();

} // namespace duckdb
